package de.symeda.sormas.backend.sample.ast;

/**
 * Antimicrobial agents supported by antibiotic susceptibility testing (AST).
 */
public enum ASTType {
	/**
	 * Macrolide antibiotic.
	 */
	AZITHROMYCIN,
	/**
	 * Oral third-generation cephalosporin.
	 */
	CEFIXIME,
	/**
	 * Injectable third-generation cephalosporin.
	 */
	CEFTRIAXONE,
	/**
	 * Fluoroquinolone antibiotic.
	 */
	CIPROFLOXACIN,
	/**
	 * Aminoglycoside antibiotic.
	 */
	GENTAMICIN,
	/**
	 * Aminocyclitol antibiotic.
	 */
	SPECTINOMYCIN,
	/**
	 * Tetracycline-class antibiotic.
	 */
	TETRACYCLINE
}
